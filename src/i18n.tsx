export const LANGUAGE_LABELS: Record<Language, string> = {
  'uz': "O'zbek",
  'ru': 'Русский',
  'en': 'English',
} as const;

export type TranslationKey = keyof typeof translations.uz;

const I18nContext = createContext<{
  language: Language;
  setLanguage: (language: Language) => void;
  t: (key: string) => string;
} | undefined>(undefined);

function getInitialLanguage(): Language {
  if (typeof window === 'undefined') return 'uz';
  const stored = window.localStorage.getItem('centr-form-language');
  if (stored === 'ru' || stored === 'en') return stored;
  return 'uz';
}

export function I18nProvider({ children }: { children: ReactNode }) {
  const [language, setLanguage] = useState<Language>(getInitialLanguage);

  useEffect(() => {
    if (typeof window !== 'undefined') {
      window.localStorage.setItem('centr-form-language', language);
    }
  }, [language]);

  const value = useMemo(() => ({
    language,
    setLanguage,
    t: (key: string) => {
      const langDict = translations[language] as Record<string, string>;
      const uzDict = translations.uz as Record<string, string>;
      return langDict[key] ?? uzDict[key] ?? key;
    },
  }), [language]);

  return <I18nContext.Provider value={value}>{children}</I18nContext.Provider>;
}

export function useTranslation() {
  const context = useContext(I18nContext);
  if (!context) {
    throw new Error('useTranslation must be used within an I18nProvider');
  }
  return context;
}
